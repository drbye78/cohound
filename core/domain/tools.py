"""Локальные инструменты оценщика: объявленный набор, вызов, результат, профиль.

Зачем отдельный носитель. Оценщик (`core/ports/llm.py::EvaluatorPort`) по I18 физически
не имеет доступа к сети: порт не принимает ``tools``/``web_search``, и это **структурная**
гарантия, а не соглашение. Но «нет веба» не означает «нет инструментов»: часть работы —
это не поиск, а **адресация** уже собранного материала (какой раздел документа содержит
фрагмент, какая шапка у таблицы, к какому столбцу относится ячейка). Такой инструмент
ничего не добывает извне: он читает корпус прогона и возвращает структурный контекст.

Поэтому инструменты живут **на стороне ядра**, а не адаптера: модель только просит вызвать
инструмент по имени, исполняет вызов pipeline (`core/pipeline/local_tools.py`), и в модель
возвращается текст результата. Адаптер LLM остаётся транспортом и по-прежнему не имеет
своего выхода в сеть.

Что здесь объявлено и почему именно так:

* :class:`ToolSpec` — **объявленный** инструмент: имя, назначение и JSON-схема аргументов.
  Модель не может вызвать инструмент, которого нет в этом наборе: набор — вход измерения, а
  не то, что модель выбрала по ходу (см. :class:`ToolProfile`).
* :class:`ToolInvocation` — запрос модели: имя + аргументы. Аргументы проверяются по схеме
  объявленного инструмента; неизвестное имя — отказ, а не «пропустим и продолжим».
* :class:`ToolOutcome` — результат: `content` (то, что видит модель) отдельно от `meta`
  (то, что видит аудит). `content` **не является доказательством**: цитата по-прежнему
  обязана быть подстрокой текста фрагмента (I22), и инструмент не создаёт фрагментов.
* :class:`ToolProfile` — профиль инструментов ячейки: какие включены и сколько вызовов
  разрешено. Это **условие измерения** и оно входит в `run_id` (см.
  `core/pipeline/digests.py`): иначе два прогона с разными инструментами жили бы под одним
  идентификатором. Бюджет вызовов — тоже условие, а не предохранитель: «не ограничивать, а
  измерять» (A3) означает, что число вызовов объявляется и публикуется, а не подрезается
  молча.

Нейтрален (§1.3): ни одного предметного термина — только имена инструментов, схема
аргументов и бюджет.
"""

from __future__ import annotations

from collections.abc import Mapping
from dataclasses import dataclass, field
from typing import Any

__all__ = [
    "NO_TOOL_PROFILE",
    "ToolInvocation",
    "ToolOutcome",
    "ToolProfile",
    "ToolSpec",
    "ToolTraceEntry",
]


@dataclass(frozen=True)
class ToolSpec:
    """Объявленный локальный инструмент: имя, назначение, схема аргументов.

    ``parameters`` — JSON Schema **объекта** аргументов (тот же вид, что принимает
    OpenAI-совместимый ``tools[].function.parameters``). Схема объявлена здесь, а не
    выводится из реализации: адаптер обязан отправлять провайдеру ровно то, что
    объявлено контрактом, иначе набор доступных вызовов описывался бы кодом, который
    исполняет вызов, — то есть менялся бы без смены идентичности прогона.
    """

    name: str
    description: str
    parameters: Mapping[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if not self.name or not self.name.islower():
            raise ValueError(f"ToolSpec: имя инструмента — slug в нижнем регистре: {self.name!r}")
        if not self.description.strip():
            raise ValueError(f"ToolSpec: у инструмента {self.name!r} пустое описание")


@dataclass(frozen=True)
class ToolInvocation:
    """Запрос модели на вызов инструмента: имя + аргументы как есть."""

    name: str
    arguments: Mapping[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if not self.name:
            raise ValueError("ToolInvocation: пустое имя инструмента")
        if not isinstance(self.arguments, Mapping):
            raise ValueError(
                "ToolInvocation: аргументы обязаны быть отображением "
                f"(получено {type(self.arguments).__name__})"
            )


@dataclass(frozen=True)
class ToolOutcome:
    """Результат вызова: что видит модель (``content``) и что видит аудит (``meta``).

    ``ok=False`` — вызов не исполнен (неизвестное имя, аргументы не по схеме, пустой
    адрес). Это **не** сбой ячейки: модель получает текст причины и продолжает. Молчаливый
    пропуск запрещён — «инструмент не ответил» и «инструмент ответил пусто» разные факты.
    """

    name: str
    content: str = ""
    meta: Mapping[str, Any] = field(default_factory=dict)
    ok: bool = True
    reason: str | None = None

    @property
    def chars(self) -> int:
        """Длина видимого модели текста — цена вызова в токенах (провенанс)."""
        return len(self.content)


@dataclass(frozen=True)
class ToolTraceEntry:
    """Запись трассы вызова — провенанс исполнения, не условие измерения.

    Трасса отвечает на вопрос «почему вердикт такой», но не входит ни в `run_id`, ни в
    `prompt_hash`: она известна только после исполнения, а идентичность обязана быть
    вычислима до него. В контракт входит **профиль** (:class:`ToolProfile`), трасса — в
    провенанс ячейки.
    """

    seq: int
    name: str
    arguments: Mapping[str, Any] = field(default_factory=dict)
    ok: bool = True
    chars: int = 0
    reason: str | None = None


@dataclass(frozen=True)
class ToolProfile:
    """Профиль инструментов ячейки: включённые инструменты и бюджет вызовов.

    Пустой профиль (``NO_TOOL_PROFILE``) — путь без инструментов: ровно то поведение,
    что было до их появления. Он обязан оставаться выразимым: тогда сравнение «с
    инструментами» и «без» — это два объявленных профиля, а не «старый код» и «новый код».

    ``max_calls`` — **объявленный** бюджет на ячейку, а не предохранитель. Исчерпание
    бюджета видно в трассе (последний ход без инструментов) и публикуется числом.
    """

    name: str = "none"
    tools: tuple[str, ...] = ()
    max_calls: int = 0

    def __post_init__(self) -> None:
        if self.max_calls < 0:
            raise ValueError(f"ToolProfile: max_calls не может быть отрицательным: {self.max_calls}")
        if self.tools and self.max_calls == 0:
            raise ValueError(
                "ToolProfile: инструменты объявлены, но бюджет нулевой — "
                "это профиль, который ничего не делает"
            )
        if not self.tools and self.max_calls:
            raise ValueError(
                "ToolProfile: бюджет объявлен без инструментов — "
                "нечего вызывать, и число вводило бы в заблуждение"
            )

    @property
    def enabled(self) -> bool:
        """Включён ли хоть один инструмент (``False`` — путь без инструментов)."""
        return bool(self.tools)

    def canonical(self) -> str:
        """Каноническая строка для дайджеста контракта (детерминированная).

        Порядок имён сортируется: профиль — множество, а не последовательность, и
        перестановка в объявлении не должна менять `run_id`.
        """
        return f"{','.join(sorted(self.tools)) or '-'};max_calls={self.max_calls}"


#: Профиль без инструментов: поведение до их появления, обязано оставаться выразимым.
NO_TOOL_PROFILE = ToolProfile()
