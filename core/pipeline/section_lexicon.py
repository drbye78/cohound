def lexicon_report() -> dict[str, Any]:
    """Отчёт о лексиконе: роли, число маркеров, полнота (видно, а не подразумевается).

    «Полнота» — не свойство словаря вообще, а проверяемое утверждение о **коде**:

    * каждая объявленная роль (:data:`SECTION_ROLES`) имеет хотя бы один маркер;
    * в :data:`ROLE_MARKERS` нет ролей, которых нет в объявлении (опечатка в ключе
      сделала бы роль недостижимой молча).

    Пустой или неполный лексикон — отказ (:func:`classify_heading` бросает
    :class:`ValueError`), а не тихая метка `unknown`: `unknown` обязан означать «маркеров
    нет в заголовке», а не «словарь не загрузился». Это различие — единственное, что
    делает ответ инструмента проверяемым.
    """
    per_role = {role: len(ROLE_MARKERS.get(role, ())) for role in SECTION_ROLES}
    missing = [role for role in SECTION_ROLES if per_role[role] == 0]
    undeclared = sorted(set(ROLE_MARKERS) - set(SECTION_ROLES))
    return {
        "roles": list(SECTION_ROLES),
        "markers": per_role,
        "missing": missing,
        "undeclared": undeclared,
        "total_markers": sum(per_role.values()),
        "complete": not missing and not undeclared and sum(per_role.values()) > 0,
    }


def _require_lexicon() -> None:
    """Отказ на пустом/неполном лексиконе (видимый, а не `unknown` по умолчанию)."""
    report = lexicon_report()
    if report["complete"]:
        return
    raise ValueError(
        "лексикон ролей раздела пуст или неполон: "
        f"роли без маркеров — {report['missing']}, необъявленные роли — "
        f"{report['undeclared']}; метка `{UNKNOWN_ROLE}` означала бы «маркеров нет в "
        "заголовке», а не «словаря нет»"
    )


def _ordered_markers(role: str) -> tuple[str, ...]:
    """Маркеры роли в детерминированном порядке: длинные первыми, при равенстве — по тексту.

    Длинный маркер первым — чтобы «not supported» срабатывал раньше, чем «supported»-
    подобное короткое вхождение внутри той же роли, и чтобы добавление короткого
    синонима не переписывало уже опубликованную метку.
    """
    return tuple(sorted(ROLE_MARKERS.get(role, ()), key=lambda marker: (-len(marker), marker)))


def classify_heading(heading: str) -> tuple[str, str]:
    """Роль раздела по заголовку: ``(роль, сработавший маркер)``.

    Возвращает ``(UNKNOWN_ROLE, "")``, когда ни один объявленный маркер не входит в
    заголовок: это факт о заголовке, а не сбой. Маркер возвращается **как записан в
    лексиконе**, а не как найден в заголовке, — ответ обязан быть воспроизводимым по
    словарю, а не по регистру корпуса.

    :raises ValueError: лексикон пуст или неполон (:func:`lexicon_report`).
    """
    _require_lexicon()
    text = (heading or "").casefold()
    if not text.strip():
        return UNKNOWN_ROLE, ""
    for role in SECTION_ROLES:
        for marker in _ordered_markers(role):
            if marker.casefold() in text:
                return role, marker
    return UNKNOWN_ROLE, ""
