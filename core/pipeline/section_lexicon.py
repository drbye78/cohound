"""Роль раздела документа по его заголовку: детерминированный лексикон (T2, план 28).

Зачем. Заголовок раздела — это **объявление автора** о том, что в разделе лежит, и оно
часто решает, что означает текст под ним. «Planned features» и «Roadmap» описывают то,
чего ещё нет; «Ограничения» описывают то, чего продукт не умеет; «Сравнение версий» —
матрицу, а не утверждение о продукте. Оценщик, читающий только текст фрагмента, этого
объявления не видит: фрагмент приходит без границы раздела, и «поддерживается» из
roadmap-раздела читается как «есть».

Что здесь **не** делается. Это не понимание и не модель: ни LLM, ни морфологии, ни
синонимов. Сопоставление — вхождение объявленного маркера в заголовок без учёта регистра,
и ответ всегда называет **сработавший маркер**: модель получает видимую причину метки, а
не догадку. Поэтому лексикон — **данные модуля** (кортежи строк), а не код: расширяется
он добавлением слова, а не правкой логики.

Почему три языка сразу. Корпуса профилей объявлены как EN/RU/ZH (§1.1 AGENTS), и
лексикон, знающий только один язык, молча помечал бы `unknown` всё остальное — то есть
его покрытие зависело бы от языка корпуса, а не от документации. `unknown` остаётся
честным ответом: «маркеров нет» — это факт о заголовке.

Нейтральность (§1.3). Маркеры — слова о **документации** («ограничения», «roadmap»,
«参考»), а не о продукте: ни одного предметного термина, ни одного названия. Один и тот
же лексикон обязан годиться любому профилю.

Что лексикон **не** различает (названный предел, а не забытое): отрицание внутри
заголовка. «Ограничения сняты» содержит маркер `ограничен` и получит метку
`limitation`, хотя говорит об обратном. Это цена детерминизма: разбирать отрицание —
значит понимать, а понимание здесь было бы вторым оценщиком. Метка видима вместе с
маркером, поэтому читатель (и модель) видит, на чём она стоит.
"""

