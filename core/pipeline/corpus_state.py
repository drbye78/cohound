"""Мутабельное состояние фазы корпуса, пересекающее границы замыканий ``_build_corpus``.

Зачем отдельный модуль. Тело :func:`core.pipeline.corpus._build_corpus` — 6 188 строк и 69
вложенных функций; девять имён текли через ``nonlocal``, то есть мутировались из замыканий
на переменных внешней функции. Это единственный вид состояния, который нельзя было
выразить явной передачей параметров: ``nonlocal`` — невидимая мутация, её не видно ни в
сигнатуре замыкания, ни в точке вызова.

:class:`CorpusCounters` делает её видимой: имя ``counters`` — обычная ссылка, а поле
``counters.<name>`` называет **что именно** меняется. Никакого поведения у объекта нет
(только поля): это данные, а не владелец логики, иначе «декомпозиция» воспроизвела бы
проблему в новой форме (god-объект вместо замыкания).

Почему не в ``corpus.py``. Следующие шаги волны выносят из тела ``_drain_root``/
``_finish_one`` (``corpus_ingest.py``/``corpus_commit.py``), и им понадобится тот же тип в
аннотациях. Объявление в ``corpus.py`` дало бы цикл: ``corpus`` → новый модуль → ``corpus``.
Модуль — лист: он не импортирует ничего из ``core.pipeline.corpus``.

**Поля — ровно те имена, что текли через ``nonlocal``** (замер AST по дереву ``962c618``,
9 имён в 8 объявлениях). Семь из них пересекают границу ``_build_corpus``; два
(``defer_extract``, ``member_pool_dead``) объявлены уровнем глубже — в ``_drain_root`` и
``_descend_container``. Они оставлены здесь, чтобы ``nonlocal`` в теле не осталось вовсе,
и помечены ниже как флаги шага, а не накопители: у объекта одно назначение — «то, что
пересекает границу замыкания», и оно шире, чем «счётчики», по факту, а не по названию.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass
class CorpusCounters:
    """Накопители и флаги одного вызова ``_build_corpus`` (мутабельные, без поведения).

    Один экземпляр на фазу. Замыкания читают его как обычную ссылку, а мутируют —
    присваиванием поля, поэтому ``nonlocal`` больше не нужен ни в одном из них.
    """

    #: Страниц, фактически добытых краулом за фазу (сумма ``Frontier.fetched`` по корням).
    #: Уходит в ``crawl_sessions.provenance_json`` при финализации сеанса: это наблюдённый
    #: объём работы, а не лимит.
    pages_fetched_total: int = 0

    #: Из них — страниц **ревалидации** (известные URL, ``revalidate``/``auto``), отдельно
    #: от discovery: смешение двух чисел скрыло бы, что бюджет ушёл на переобход известного.
    revalidation_fetched_total: int = 0

    #: Сколько seed'ов поставлено в очередь **в текущем продукте** (авторские + sitemap).
    #: Сбрасывается на каждом продукте; нужен честной причине ``zero_source``:
    #: «корней нет», «seed'ы не заданы» и «все seed'ы отклонены» — разные утверждения.
    product_seeds_enqueued: int = 0

    #: Сеанс краула закрыт (:func:`_finalize_crawl_session` вызывается дважды — на границе
    #: краула и в ``finally``; второй вызов обязан быть no-op, а не переписать терминальный
    #: статус).
    session_finalized: bool = False

    #: Максимум разрешённого окна экстракции по корням (``None`` — ни один корень не
    #: объявлял окна). Максимум, а не последнее значение: пул фазовый, фактическая ширина
    #: параллелизма — самая широкая из использованных.
    observed_extract_workers: int | None = None

    #: Максимум ``extract_max_tasks_per_child`` по корням (``None`` — рециклинга не было).
    observed_extract_max_tasks: int | None = None

    #: Хотя бы на одном корне окно выведено из бюджета памяти, а не объявлено оператором:
    #: источник расписания в метриках тогда ``derived``, а не ``declared``.
    observed_extract_derived: bool = False

    #: Флаг шага, **не** накопитель: экстракция текущего элемента корня идёт в пул
    #: (снимается inline-fallback'ом при отказе пула). Присваивается на каждом элементе
    #: перед его обработкой — поэтому значение не «переживает» элемент.
    defer_extract: bool = False

    #: Флаг шага, **не** накопитель: пул экстракции текущего спуска признан мёртвым
    #: (``2 × timeout`` без завершений) — остаток членов контейнера пропускается видимо,
    #: а не ждёт таймаут на каждом. Переинициализируется перед каждым спуском.
    member_pool_dead: bool = False
