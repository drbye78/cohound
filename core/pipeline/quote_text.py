"""Нормализация текста для поиска цитаты — одна на оба прибора retrieval-эталонов.

**Зачем отдельный модуль.** Документный эталон (`scripts/prepare_retrieval_golden_docs.py`,
правило A) и чанковый (`scripts/prepare_retrieval_golden_chunks.py`) отвечают на один
вопрос: «лежит ли эта цитата буквально в этом тексте?». Пока нормализация жила в одном
скрипте, второй прибор написал бы свою — и два прибора разошлись бы молча: один нашёл бы
цитату там, где другой её не видит, а расхождение выглядело бы как свойство корпуса, а не
как расхождение прибора. Поэтому правило живёт здесь, в нейтральном слое, и оба берут его
отсюда.

**Чем это не `normalize_quote_text` из** :mod:`core.pipeline.validate`. Тот — контракт
оценщика (§7.1 п. 4): только пробельные серии, и менять его значит менять смысл вердиктов.
Здесь нормализация шире на одно правило, замеренное отдельно (O16): `\\_` → `_`, потому что
документация пишет экранированный underscore, и буквальная подстрока `pg_basebackup`
такого текста не видит (замер 15.11.2026: 810 «чистых» чанков против 930 экранированных).

**Карта смещений.** :func:`normalize` возвращает не только нормализованный текст, но и
«нормализованный индекс → индекс в исходном тексте»: по ней найденное вхождение
переводится обратно в смещения документа (чанковый прибор пересекает его с отрезками
чанков). Документному прибору нужен только сам текст, но карта считается за ту же цену.

Нейтрален к предметной категории (§1.3): только текст.
"""

from __future__ import annotations

__all__ = ["normalize"]


def normalize(text: str) -> tuple[str, list[int]]:
    """Нормализует текст для поиска цитаты и возвращает карту «норм. индекс → исходный».

    Две нормализации, обе замеренные, а не вкусовые:

    * пробельные серии → один пробел: цитата склеивается из строки промпта, где переводы
      строк и отступы не совпадают с текстом чанка;
    * ``\\\\_`` → ``_``: документация пишет экранированный underscore, и буквальная
      подстрока ``pg_basebackup`` такого чанка не видит (замер O16 15.11.2026: 810
      «чистых» чанков против 930 экранированных).

    Регистр и пунктуация **не** нормализуются: цитата — то, что оценщик прочитал в чанке,
    и «нашлось после смены регистра» — другой факт, который не должен выглядеть как
    попадание.
    """
    out: list[str] = []
    index: list[int] = []
    position = 0
    length = len(text)
    while position < length:
        char = text[position]
        if char == "\\" and position + 1 < length and text[position + 1] == "_":
            out.append("_")
            index.append(position)
            position += 2
            continue
        if char.isspace():
            end = position
            while end < length and text[end].isspace():
                end += 1
            out.append(" ")
            index.append(position)
            position = end
            continue
        out.append(char)
        index.append(position)
        position += 1
    start = 0
    stop = len(out)
    while start < stop and out[start] == " ":
        start += 1
    while stop > start and out[stop - 1] == " ":
        stop -= 1
    return "".join(out[start:stop]), index[start:stop]
