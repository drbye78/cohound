"""Порты локальных инструментов оценщика (§7, I17/I18).

Две вещи, которые нельзя смешивать:

* :class:`LocalToolPort` — **что модель может вызвать**: объявленный набор
  (:class:`~core.domain.tools.ToolSpec`) и исполнение вызова по имени. Реализация живёт в
  ядре (`core/pipeline/local_tools.py`) и читает только корпус прогона; сеть ей не нужна и
  не предоставляется.
* :class:`ToolCorpusPort` — **что инструменту разрешено читать**: узкое окно в корпус
  прогона (чанки документа, чанки раздела, таблицы документа). Окно узкое намеренно: если
  бы инструмент получал полный `StorePort`, он мог бы писать, менять состояние прогона или
  ходить в другие продукты — то есть нарушать I17 (продуктовая привязка ретривала) уже не
  по решению, а по возможности.

I18 остаётся структурной. Порт инструментов не принимает URL, не отдаёт байты страниц и
не умеет «сходить и посмотреть»: он умеет адресовать уже извлечённое. Веб-доступ
по-прежнему живёт только в DMZ (`core/edge/`) и только на этапе краула.
"""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass
from typing import Protocol, runtime_checkable

from core.domain.doc_tables import ExtractedTable, TableKey, TableRef
from core.domain.tools import ToolInvocation, ToolOutcome, ToolSpec, ToolTraceEntry
from core.ports.types import Chunk

__all__ = ["LocalToolPort", "ToolCallRecord", "ToolCorpusPort"]


@dataclass(frozen=True)
class ToolCallRecord:
    """Строка трассы вызова инструмента: **адрес ячейки** + запись вызова (план ``28`` §9).

    Трасса — провенанс, а не условие измерения: она отвечает «почему вердикт такой» и
    «сколько вызовов стоил прогон», но в ``run_id`` не входит (тот вычислим до исполнения).
    ``entry.seq`` — порядок вызова внутри ячейки и часть первичного ключа таблицы
    ``cell_tool_calls``.

    ``product_id``/``param_id`` живут здесь, а не в :class:`~core.domain.tools.ToolTraceEntry`:
    запись вызова — про сам вызов (имя, аргументы, результат), адрес ячейки — про то, где он
    случился. Смешать их значило бы дать доменному типу знание о раскладке ячеек.

    **Почему объявлено в портах, а не в хранилище.** Строку собирает ``pipeline``
    (:func:`core.pipeline.evaluate.evaluate_batch`), а пишет/читает ``store``. Импорт
    ``pipeline → store`` запрещён матрицей слоёв (§4.1, гейт ``selfcheck._import_graph``),
    поэтому общий носитель живёт на уровне контракта; ``core.store.sqlite_store``
    реэкспортирует его, чтобы прежние импорты не сломались.
    """

    product_id: str
    param_id: str
    entry: ToolTraceEntry


@runtime_checkable
class ToolCorpusPort(Protocol):
    """Чтение корпуса прогона для инструментов: только чтение и только один продукт.

    Все методы возвращают **пустую** последовательность, если адрес неизвестен, и
    ``None`` — там, где различие «нет данных» и «данных не бывает» существенно
    (``document_tables``: ``None`` — читатель таблиц не даёт, ``()`` — искал и не нашёл).
    """

    def section_chunks(self, chunk_id: str) -> Sequence[Chunk]:
        """Чанки **поддерева** раздела адресованного чанка, по ``chunk_no``.

        Поддерево — чанки с тем же ``heading_path``, с родительским и с дочерним:
        общая оговорка раздела живёт в родителе, конкретика — в подразделе, и оба нужны,
        чтобы ответить «что говорит документ про этот раздел». Родство — по границе пути
        заголовков, а не по символу. Пустой путь — пролог документа, а не всякий раздел.

        Порядок — ``chunk_no``. Пустая последовательность — адрес неизвестен или раздела
        нет. Объём ограничен бюджетом инструмента, а не этим методом: обрезка видима
        вызывающему (``meta``), тихой потери нет.
        """
        ...

    def document_chunks(self, chunk_id: str) -> Sequence[Chunk]:
        """Все чанки документа адресованного чанка, по ``chunk_no``."""
        ...

    def document_tables(self, chunk_id: str) -> tuple[ExtractedTable, ...] | None:
        """Таблицы документа адресованного чанка (``None`` — читатель их не даёт)."""
        ...

    def table_context(
        self, chunk_ids: Sequence[str]
    ) -> tuple[dict[str, TableRef | None], dict[TableKey, ExtractedTable]]:
        """Адреса таблиц пачкой: ``chunk_id → TableRef|None`` и карта таблиц документов.

        Один вызов на ячейку вместо двух чтений на фрагмент: срез — до ``cutoff_K``
        фрагментов, и поштучные запросы умножали бы цену на их число. Возвращаются две
        вещи, потому что они нужны вместе и разного происхождения:

        * первый словарь — адрес **фрагмента** (``corpus_chunks.table_ref``). Ключ есть
          только у чанков **этого** продукта (I17) и только у тех, что реально нашлись в
          корпусе прогона: чужой/неизвестный адрес в словарь не попадает, и «его нет в
          корпусе» отличимо от «адрес неизвестен» (``None``);
        * второй — объекты таблиц ``(документ, table_id) → ExtractedTable`` **только для
          документов, где адрес реально встретился**: читать таблицы всех документов среза
          значило бы платить за материал, который в промпт не пойдёт. Ключ парный
          (:data:`~core.domain.doc_tables.TableKey`): ``table_id`` локален для документа.

        Порча JSON/отсутствие колонки читаются как «адрес неизвестен» (``None``), а не
        исключением: ответ инструмента и промпт не должны зависеть от целостности колонки
        (та же дисциплина, что у :meth:`document_tables`).
        """
        ...

    def chunk(self, chunk_id: str) -> Chunk | None:
        """Чанк по адресу (``None`` — адреса нет в корпусе этого прогона)."""
        ...


@runtime_checkable
class LocalToolPort(Protocol):
    """Объявленный набор локальных инструментов и исполнение вызова.

    Контракт исполнения: неизвестное имя и аргументы не по схеме дают
    ``ToolOutcome(ok=False, reason=…)``, а **не** исключение — модель обязана увидеть
    причину и продолжить. Исключение здесь означало бы, что поведение ячейки зависит от
    того, что модель попросила, то есть набор доказательств перестал бы быть функцией
    объявленных входов.
    """

    def specs(self) -> tuple[ToolSpec, ...]:
        """Объявленные инструменты профиля (пустой кортеж — инструментов нет)."""
        ...

    def invoke(self, invocation: ToolInvocation) -> ToolOutcome:
        """Исполнить вызов; неизвестное имя/плохие аргументы — ``ok=False`` с причиной."""
        ...
