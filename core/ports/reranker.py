    """Пары ``(запрос, документы)`` → балл на документ; порядок сохраняется.

    :param query: текст запроса (один на вызов; несколько запросов ячейки вызывающий
        объединяет сам — политика слияния принадлежит ему, а не порту).
    :param documents: тексты кандидатов в порядке выдачи плеча.

    :raises ValueError: длина результата ≠ длине ``documents`` или балл не конечен.
    """

    #: ``repo@revision`` — веса, которыми считался балл (провенанс, §13).
    model_id: str
    #: Объявленное устройство счёта (``cpu``/``cuda``): место вычисления — условие замера.
    device: str

