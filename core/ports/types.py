@dataclass(frozen=True)
class FetchPlan:
    """План получения и извлечения страницы (D2/D4).

    Оси: ``fetch`` (:class:`~core.domain.enums.FetchMode` — **нужен ли браузер вообще**),
    ``extract`` (:class:`~core.domain.enums.ExtractionRoute` — авто/HTML/документ) и
    ``strategy`` (:class:`~core.domain.enums.CrawlStrategy` — **как** браузер используется
    **при browser-capable адаптере**; при ``fetch=HTTP`` нормализуется в ``AUTO``), плюс
    опциональное JS-условие ожидания для браузерного рендера и опциональный per-host
    диапазон задержек ``rate_limit``. Единый value-объект резолвится в pipeline
    (:func:`core.pipeline.fetch_plan.resolve_fetch_plan`) и передаётся и краулеру, и
    экстрактору — адаптеры сами план не строят.

    ``engine`` — идентификатор движка/транспорта краула, фактически использованного для
    страницы (напр. ``http``/``scrapy``/``browser``): свободная строка-данные, валидируется
    composition root, **не** доменный enum.

    ``robots`` — флаг egress-вежливости (§10): адаптер проверяет ``robots.txt`` только
    если у него **есть** политика (``_robots is not None``) **и** ``robots`` истинно.
    Дефолт ``False`` сохраняет обратную совместимость (никаких лишних fetch ``robots.txt``).

    ``if_none_match``/``if_modified_since`` — **условный запрос** (additive): значения
    заголовков ``If-None-Match``/``If-Modified-Since`` из валидаторов предыдущего
    получения (``RawPage.etag``/``RawPage.last_modified``). ``None`` (дефолт) — обычный
    безусловный GET, байт-идентичный прежнему поведению.
    """

    fetch: FetchMode = FetchMode.HTTP
    extract: ExtractionRoute = ExtractionRoute.AUTO
    wait_for: str | None = None
    strategy: CrawlStrategy = CrawlStrategy.AUTO
    rate_limit: RateLimitSpec | None = None
    engine: str | None = None
    robots: bool = False
    if_none_match: str | None = None
    if_modified_since: str | None = None
    #: P0/OOM: потолок одного ответа (байты) для этого запроса. ``None`` — адаптер
    #: применяет собственный дефолт (20 MiB). Резолвится из ``CrawlLimits`` per seed-root
    #: и переносится на план, чтобы per-site ось дошла до транспорта. Это **in-memory**
    #: потолок: страница свыше него — ``payload_too_large``.
    max_response_bytes: int | None = None
    #: P6b: каталог staging для допущенного терминального артефакта (документ
    #: pdf/docx/pptx/xlsx либо заявленный контейнер). Задан **только** для артефактов:
    #: адаптер, умеющий стримить, кладёт тело в файл этого каталога, а не в RAM.
    #: ``None`` (дефолт) — поведение страницы байт-в-байт.
    staging_dir: str | None = None
    #: P6/P6b: потоковый потолок терминального артефакта (байты). Действует, только когда
    #: задан ``staging_dir``; превышение — ``payload_too_large`` (видимый отказ, без файла).
    max_stream_bytes: int | None = None
    #: P6: заявленный набор форматов-контейнеров (``crawl.attachment_formats``). Адаптер
    #: решает класс ответа по URL-суффиксу **или** ``Content-Type`` (суффикс-less
    #: download-эндпоинты): только терминальный артефакт (документ или заявленный
    #: контейнер) вправе уйти в staging-файл. ``None`` — дефолтный набор всех
    #: поддерживаемых контейнеров (так резолвится конфиг); пустой кортеж — контейнеры не
    #: заявлены (документная часть класса от набора не зависит).
    attachment_formats: tuple[str, ...] | None = None


@dataclass(frozen=True)
class RawPage:
    """Сырая страница — retention-единица (§3.2). ``content`` хранится как байты.

    ``engine`` — идентификатор движка/транспорта, фактически доставившего байты (свободная
    строка-данные, валидируется composition root; **не** доменный enum).

    ``etag``/``last_modified`` — **валидаторы ответа** для условного повторного получения
    (заголовки ``ETag``/``Last-Modified``): их передают обратно в
    :attr:`FetchPlan.if_none_match`/:attr:`FetchPlan.if_modified_since` при следующем
    цикле. ``None`` — сервер валидаторов не дал (или транспорт их не видит).

    ``not_modified`` — сервер подтвердил (``304``), что закэшированное представление
    актуально. Тогда ``content`` — **байты из кэша** (никогда не пустое тело и не
    сфабрикованный ответ); pipeline может пропустить retention/экстракцию. ``False``
    (дефолт) — обычный ответ с новым телом.

    ``from_cache`` — страница отдана локальным R7-кэшем (``cache/http``): сеть в этом
    вызове не трогалась, шов не дёргался. Провенанс такой страницы —
    ``reuse_kind=reused``, а не ``live``: наблюдения в этом цикле не было. ``False``
    (дефолт) — байты получены живым запросом (в том числе ``304``, где сервер ответил).

    **Файловый staging (P6).** Допущенный артефакт-контейнер (``zip``/``7z``/``rar``)
    может не помещаться в память: тогда адаптер пишет тело в ``staged_path`` (файл
    вызывающего каталога) и оставляет ``content`` **пустым**, а ``head`` — первыми
    8 KiB (классификация/сниф без чтения файла). ``staged_path is None`` — обычная
    страница, ``content`` несёт байты (байт-идентично прежнему поведению).

    **I19.** ``staged_path`` — недоверенный вход: pipeline **сам** пере-хеширует файл
    (потоково) и публикует его в ``corpus_raw``; хеш от адаптера не принимается (его
    здесь и нет). Файл staging после публикации переезжает, а не копируется.

    **Путь к retained-байтам (``source_path``).** Когда задан, экстрактор **может**
    читать файл вместо ``content``, а ``content`` при этом может быть пустым: документ
    не поднимается в RAM воркера только ради передачи его адаптеру (docling всё равно
    читает файл с диска). Это тот же файл, чей хеш — идентичность retention (I19):
    ``corpus_raw/{product_id}/{sha256}.bin``, поэтому чтение с диска сохраняет, а не
    ослабляет верификацию. ``None`` (дефолт) — прежнее поведение: байты в ``content``,
    все существующие вызовы остаются байт-в-байт неизменными.
    """

    url: str
    content: bytes
    fetched_at: str
    #: Ось получения — **наблюдение**, а не дефолт: ``None`` означает «получения не было»
    #: (ручная подача артефакта оператором: байты предъявил человек, сервер не отвечал).
    #: Подставить ``http`` здесь значило бы записать ложный провенанс в ``corpus_docs``,
    #: поэтому ``None`` — законное значение поля, а не «поле осталось незаполненным».
    fetch_mode: FetchMode | None = FetchMode.HTTP
    lang: str | None = None
    status_code: int | None = None
    content_type: str | None = None
    engine: str | None = None
    etag: str | None = None
    last_modified: str | None = None
    not_modified: bool = False
    #: Страница получена из локального R7-кэша (``cache/http``), сеть в этом вызове не
    #: трогалась; провенанс такой страницы — ``reuse_kind=reused``, а не ``live``.
    from_cache: bool = False
    staged_path: str | None = None
    head: bytes | None = None
    #: Путь к retained-байтам этой страницы (``corpus_raw``). Задан — экстрактор вправе
    #: читать файл вместо ``content`` (``content`` может быть пустым); ``None`` — байты в
    #: ``content`` (прежнее поведение).
    source_path: str | None = None


#: Причина отказа :class:`ExtractedDoc`: документ **добыт**, но текста в нём нет.
#:
#: Объявлена рядом с носителем, потому что структурированного признака «пустой артефакт»
#: у ``ExtractedDoc`` нет: любой отказ адаптера возвращает пустой ``text`` и заполненный
#: ``error``, поэтому отличить «нечего разбирать» от «парсер сломался» можно только по
#: причине. Классификация (:attr:`core.domain.FailureKind.EMPTY_DOCUMENT`) сравнивает
#: причину именно с этой константой — вторая копия строки разошлась бы с первой молча.
EMPTY_TEXT_REASON = "текст пуст"


@dataclass(frozen=True)
class ExtractedDoc:
    """Нормализованный документ после экстракции (§3.5).

    ``error`` — грациозная деградация адаптера: сбой извлечения возвращает пустой ``text``
    и заполненный ``error``, а не исключение (см. ``adapters/extract_document.py``).

    ``family`` — **семейство формата** извлечённого текста (``"markdown"``/``"text"``/
    ``"epub"``, константы ``core.util.document_formats``) — вход выбора чанкера в
    composition root: markdown/HTML/EPUB режутся по заголовкам, plain text — по абзацам.
    ``None`` (дефолт) означает «markdown-совместимое семейство»: так ведут себя HTML и
    docling (оба отдают markdown), поэтому существующие пути байт-в-байт неизменны.

    **Частичность (``partial``/``partial_reason``).** Документ прочитан **не целиком**, но
    прочитанное — настоящий текст: docling вернул ``PARTIAL_SUCCESS`` (часть страниц не
    сконвертирована), pdfium не прочитал часть страниц. Это **не** ``error``: текст есть и
    обязан попасть в корпус — иначе доказательство, которое было прочитано, исчезает, а
    ячейка получает «материала нет». Но и не полный успех: ``partial`` — видимый факт
    провенанса, а не тихая подмена (уровень ``full``/``layout*``, обещавший структуру
    целого документа, при частичном результате ею не является — это читается в
    ``partial_reason``).

    Инвариант (проверяется :meth:`__post_init__`): ``partial=True`` требует непустого
    ``text`` и ``error is None`` — «частичный успех» без текста есть провал, а не успех;
    ``partial_reason`` без ``partial`` — ложная провенанс-запись. Счётчики страниц
    (``page_count``/``pages_converted``) не могут противоречить друг другу, а
    ``pages_converted`` без ``partial`` — счётчик без факта. Карта страниц
    (:attr:`page_map`) и блоки (:attr:`blocks`) проверяются там же: они либо точны, либо
    ``None``.
    """

    text: str
    content_hash: str
    extractor_version: str
    page_count: int | None = None
    error: str | None = None
    family: str | None = None
    #: Документ прочитан частично (часть страниц/членов не сконвертирована), текст — реален.
    partial: bool = False
    #: Почему частично: статус движка + сколько страниц получено + уровень, который обещался.
    partial_reason: str | None = None
    #: Сколько страниц **реально** попало в текст (``page_count`` — сколько заявлено
    #: документом). Пара нужна, чтобы «частично» было числом, а не прилагательным:
    #: без неё человек не отличит «не прочиталась одна страница из семи» от «не
    #: прочиталось 662 из 665». ``None`` — движок числа не сообщает; выдумывать нельзя
    #: (A3), а ``page_count - 1`` не является измерением.
    pages_converted: int | None = None
    #: Исход проверки OCR-движка (значения — :data:`OCR_PROBE_VALUES`, канон —
    #: :mod:`core.domain.ocr_probe`: то же значение проверяет ``CorpusDoc``). ``None`` —
    #: проверка к документу **не применима** (не PDF либо уровень без OCR); ``"unknown"``
    #: — её не было или результат не сохранён (старый конверт ``extract_cache``). Отдельное
    #: поле, а не молчание: «не проверено» не должно читаться как «проверено и работает» —
    #: иначе переименование приватного API docling снова пройдёт незамеченным.
    #: Стоит в конце: позиционные конструкторы не должны поехать от появления провенанса.
    ocr_probe: str | None = None
    #: Карта страниц: ``(page_no, char_start, char_end)`` — номер страницы (**1-based**) и
    #: **полуоткрытый** интервал ``[char_start, char_end)`` её собственного текста.
    #:
    #: **Пространство координат** — то же, в котором живут :attr:`Chunk.char_start`/
    #: ``char_end``: :attr:`text` **без ведущего BOM**. Чанкер снимает ``\\ufeff``
    #: (:func:`core.adapters.chunker_text._normalize`), а
    #: :func:`~core.util.sanitize.finalize_extracted_text` его не снимает; поэтому читатель,
    #: чей текст начинается с BOM, сдвигает все смещения на −1. Без сдвига ``page_number``
    #: чанка уезжал бы на единицу — молча и на всём документе.
    #:
    #: **Разделитель страниц — разрыв карты, а не её часть.** Сегменты покрывают текст
    #: страницы, а ``\\n\\n`` между страницами в карту не входит. Отсюда правило для
    #: потребителя (вывод номера страницы по ``char_start``): смещение, попавшее в разрыв,
    #: принадлежит **следующей** странице, а смещение за последним сегментом — **последней**.
    #: Пустая страница — это ``start == end``: страница прочитана, текста в ней нет; это
    #: факт, а не разрыв.
    #:
    #: Само правило вывода — одна функция, :func:`core.domain.page_map.page_number_for`
    #: (включая случай пустого сегмента и отсутствующей карты): номер страницы — функция
    #: от карты и ``char_start``, а не колонка, которую обязан поддерживать каждый путь
    #: записи чанка.
    #:
    #: ``None`` — читатель карту **не дал** (сегодня так делают все, кроме ``text_layer``):
    #: это не «страниц нет» и не «одна страница». Выдуманный номер хуже отсутствующего (A3),
    #: поэтому ``None`` честнее догадки.
    #:
    #: В ``content_hash`` карта **не входит**: хеш описывает текст, а карта — провенанс.
    #: Иначе один и тот же текст давал бы разные хеши у разных механизмов (и один документ
    #: — разные ключи ``extract_cache``).
    page_map: tuple[tuple[int, int, int], ...] | None = None
    #: Сколько страниц дали **хотя бы одну OCR-ячейку** (O38a, план ``26``): страница, для
    #: которой движок заполнил ``ocr_score``. ``None`` — **не применимо или не измерено**:
    #: не PDF, уровень без OCR (``layout``/``layout_tables``/``text``), читатель, который
    #: об OCR ничего не сообщает (``text_layer``, HTML, Office, EPUB).
    #:
    #: ``0`` — не заглушка, а факт: OCR **применялся** (уровень ``full``) и не дал ни одной
    #: страницы — документ целиком прочитан из текстового слоя. Смешивать эти два случая
    #: нельзя: «неприменимо» и «применили и не понадобилось» — разные наблюдения.
    #:
    #: Чего здесь **нет** и почему: «текст страницы получен OCR-ом» (``TextCell.from_ocr``)
    #: docling отдаёт только при ``generate_parsed_pages=True``, а пайплайн обнуляет
    #: ``page.parsed_page`` ⇒ посимвольное происхождение текста страницы сегодня
    #: недоступно; это отдельная ось с ценой по RSS и отдельным замером (A3). «OCR смотрел
    #: и текста не дал» библиотека не сообщает вовсе (только warning в лог) — публиковать
    #: это как ``0`` было бы выдумкой.
    pages_ocr: int | None = None
    #: Сколько **страниц** попало в ``result.errors`` docling с непустым ``page_no``
    #: (ошибка уровня документа, ``page_no=None``, сюда не входит). ``None`` — не
    #: применимо либо не измерено (не docling-путь).
    #:
    #: Считаются **страницы**, а не ошибки: на одной странице их может быть несколько, и
    #: «три ошибки» не значит «три страницы». ``partial`` для этого факта **не** требуется:
    #: страница может упасть, а документ остаться полным по статусу — это независимое
    #: наблюдение, а не производная от частичности.
    pages_failed: int | None = None
    #: Таблицы документа как **объекты** (O39 фаза 1 плана ``26``): шапка, строки данных,
    #: подпись и страница каждой таблицы. Носитель — :class:`core.domain.doc_tables.ExtractedTable`
    #: (определён в домене, потому что у факта два носителя: здесь и в строке корпуса;
    #: реэкспорт ради того, чтобы читатель видел тип рядом с документом).
    #:
    #: ``None`` и ``()`` — **разные факты**, и это главное в поле: ``None`` — читатель
    #: таблиц **не даёт вовсе** (``text_layer``/pdfium таблиц не распознаёт, HTML, EPUB,
    #: офисный путь docling, шов ``split``); ``()`` — читатель искал и не нашёл ни одной.
    #: Свести их к одному значило бы публиковать «таблиц нет» там, где их никто не искал.
    #:
    #: В ``content_hash``/``run_id`` таблицы **не** входят: это наблюдение о прочитанном,
    #: а не условие измерения, — ровно как ``page_map``/``ocr_probe``. Нарезка чанков от
    #: этого поля не зависит: генерация чанков из таблицы — отдельная фаза (O39 фаза 2).
    tables: TableList | None = None
    #: Структурные блоки документа (O36 фаза 2 плана ``26``): вид фрагмента, его отрезок,
    #: страница, рамка, родитель, порядок чтения и **происхождение текста**
    #: (``read`` — прочитан слоем/разметкой, ``reconstructed`` — собран моделью из
    #: раскладки). Носитель — :class:`core.domain.doc_blocks.ExtractedBlock` (определён в
    #: домене, потому что у факта два носителя: здесь и в строке корпуса).
    #:
    #: ``None`` и ``()`` — **разные факты**: ``None`` — читатель блоков **не даёт вовсе**
    #: (HTML, текст/markdown, EPUB, Office, шов ``split``, docling — см. докстринг
    #: ``core.adapters.extract_document``), ``()`` — смотрел и блоков не дал. Свести их к
    #: одному значило бы публиковать «блоков нет» там, где их никто не искал (A3).
    #:
    #: Смещения — в пространстве **чанкера** (тот же контракт, что у :attr:`page_map`:
    #: полуоткрытые отрезки, без ведущего BOM), поэтому читатель сдвигает их так же, как
    #: карту страниц. Адрес блока у **чанка** — функция от этого списка и ``char_start``
    #: (:func:`core.domain.doc_blocks.block_id_for`), а не колонка: копию пришлось бы
    #: поддерживать на каждом пути записи чанка (см. :mod:`core.domain.page_map`).
    #:
    #: В ``content_hash``/``run_id`` блоки **не** входят: это наблюдение о прочитанном, а
    #: не условие измерения (как ``page_map``/``tables``), и нарезка чанков от них не
    #: зависит.
    blocks: BlockList | None = None

    def __post_init__(self) -> None:
        """Держит инвариант частичности и проверяет провенанс OCR.

        Частичность не бывает пустой и не бывает без текста; ``ocr_probe`` принимает
        только объявленные значения — иначе «не проверено» не отличить от «проверено»;
        ``page_map`` либо точна (отсортирована, не пересекается, лежит в тексте), либо
        ``None`` — «читатель её не дал».

        Проверка здесь, а не в адаптере, потому что ``ExtractedDoc`` пересекает шов и кэш:
        «частичный» документ без текста и «полный» документ с причиной частичности —
        одинаково ложные провенанс-записи, независимо от того, кто их собрал.
        """
        # Счётчики страниц — факты, а не оценки: противоречивая пара (прочитано больше,
        # чем заявлено документом, либо отрицательное) — ложная провенанс-запись.
        check_ocr_probe(self.ocr_probe)
        # Исходы OCR по страницам (O38a): неотрицательны и не больше числа страниц
        # документа. ``partial`` для них **не** требуется — упавшая страница при полном
        # статусе документа такое же наблюдение, как и любое другое, и связывать его с
        # частичностью значило бы выдумать причину.
        for name, value in (
            ("pages_ocr", self.pages_ocr),
            ("pages_failed", self.pages_failed),
        ):
            if value is None:
                continue
            if value < 0:
                raise ValueError(
                    f"ExtractedDoc: {name} отрицателен — число страниц не может быть "
                    "меньше нуля"
                )
            if self.page_count is not None and value > self.page_count:
                raise ValueError(
                    f"ExtractedDoc: {name} больше page_count — страниц с этим исходом "
                    "не может быть больше, чем страниц в документе"
                )
        if self.page_map is not None:
            # Карта страниц — либо точная, либо отсутствует: см. докстринг поля.
            # Инвариант живёт в домене (``core.domain.page_map``): у карты два носителя,
            # и две копии валидатора разошлись бы молча.
            check_page_map(self.page_map, len(self.text))
        if self.blocks is not None:
            # Блоки — тот же принцип: либо точный список, либо ``None`` («читатель блоков
            # не даёт»). Инвариант один на два носителя (``core.domain.doc_blocks``).
            check_blocks(self.blocks, len(self.text))
        if self.pages_converted is not None:
            if self.pages_converted < 0:
                raise ValueError(
                    "ExtractedDoc: pages_converted отрицателен — число прочитанных "
                    "страниц не может быть меньше нуля"
                )
            if self.page_count is not None and self.pages_converted > self.page_count:
                raise ValueError(
                    "ExtractedDoc: pages_converted больше page_count — прочитано больше "
                    "страниц, чем документ заявляет"
                )
        if not self.partial:
            if self.partial_reason is not None:
                raise ValueError(
                    "ExtractedDoc: partial_reason задан при partial=False — "
                    "причина частичности без самой частичности"
                )
            if self.pages_converted is not None:
                raise ValueError(
                    "ExtractedDoc: pages_converted задан при partial=False — "
                    "счётчик прочитанных страниц без частичности"
                )
            return
        if self.error is not None:
            raise ValueError(
                "ExtractedDoc: partial=True вместе с error — частичный успех и сбой "
                "одновременно несовместимы"
            )
        if not self.text.strip():
            raise ValueError(
                "ExtractedDoc: partial=True с пустым text — частичного успеха без текста "
                "не бывает (это провал, error)"
            )


@dataclass(frozen=True)
class Chunk:
    """Единица индексации (§4.4). ``text`` — чистый текст для валидации цитат.

    ``char_start``/``char_end`` — **смещения куска в нормализованном тексте документа**
    (:attr:`ExtractedDoc.text`), том самом, из которого собран ``text``. Это провенанс, а
    не ось нарезки: он позволяет проверить, что цитата (I22) стоит в документе там, где ей
    место, и пере-срезать кусок, не пере-нарезая документ.

    Инвариант: **если оба заданы —** ``doc.text[char_start:char_end] == text``. ``None``
    (дефолт) означает «кусок не является точным срезом»: так адаптер может объявить
    границу честно, а не выдумать позицию (A3). Оба штатных чанкера
    (``md-ast-1``/``text-para-4``) смещения заполняют: их ``text`` — точный срез входа.
    Поля стоят **в конце**: позиционные конструкторы не должны поехать от появления
    провенанса.
    """

    chunk_id: str
    chunk_no: int
    text: str
    heading_path: str
    context_prefix: str
    content_hash: str
    char_start: int | None = None
    char_end: int | None = None


