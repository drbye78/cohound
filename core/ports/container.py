"""Порт контейнеров-архивов — ``ContainerPort`` (спуск, срез B2).

Контейнер (``zip``/``7z``/``rar``) — **терминальный артефакт**: его байты не продолжают
навигацию, а служат входом для спуска. Порт отделяет «спуск» от библиотеки-читателя:
замена читателя (stdlib ``zipfile``, ``py7zr``, ``rarfile``, внешний ``7z``-бинарь) —
commodity-слой (A2), методологию не меняет.

**Инвариант (a) — листинг не есть извлечение.** :meth:`ContainerPort.list_members` читает
**только индекс контейнера** (zip central directory, 7z header, RAR header) и никогда —
тела членов. Поэтому «сколько и чего внутри» дёшево и безопасно: листинг 4 GiB архива не
распаковывает ни байта. Размер члена (:attr:`ContainerMember.size`) — **заявленный**
размер из индекса самого контейнера, а не измеренный распаковкой; доверять ему можно лишь
как **первому** гейту (bomb-guard — политика, см. ``core.util.container_policy``).

**Инвариант (b) — ``open_member`` стримит.** :meth:`ContainerPort.open_member` отдаёт
итератор чанков и **не** требует держать в памяти ни член целиком, ни (тем более) архив
целиком. Потребитель обязан применять жёсткий байтовый потолок на чтении
(``container_policy.bounded_iter``), потому что заявленный размер — не гарантия.

Нейтрален (§1.3): в модуле нет предметных терминов; импорты — только stdlib (слой
``ports``).
"""

from __future__ import annotations

from collections.abc import Iterator
from dataclasses import dataclass
from typing import Protocol, runtime_checkable

__all__ = ["ContainerListing", "ContainerMember", "ContainerPort", "ContainerUnavailable"]


class ContainerUnavailable(RuntimeError):
    """Бэкенд контейнера недоступен (пакет/внешняя утилита отсутствует).

    ``list_members`` в этой ситуации **не** бросает — он возвращает ``unreadable``.
    Исключение нужно там, где листинга нет по определению: :meth:`ContainerPort.
    open_member`. ``reason`` — та же видимая формулировка (``backend_unavailable: ...``),
    чтобы потребитель мог превратить её в пропуск спуска без разбора текста исключения.
    """

    def __init__(self, reason: str) -> None:
        super().__init__(reason)
        self.reason = reason


@dataclass(frozen=True)
class ContainerMember:
    """Член контейнера по данным **индекса** (не распаковки).

    ``path`` — путь внутри контейнера как он объявлен (сырой, до нормализации:
    ``normalize_member_path`` решает, годится ли он как имя); ``size`` — **заявленный**
    несжатый размер из индекса; ``compressed_size`` — заявленный сжатый размер
    (``None``, если бэкенд его не отдаёт); ``crc32`` — контрольная сумма из индекса
    (``None``, если бэкенд её не отдаёт); ``is_dir`` — запись-каталог (тела нет).
    """

    path: str
    size: int
    compressed_size: int | None
    crc32: int | None
    is_dir: bool


@dataclass(frozen=True)
class ContainerListing:
    """Индекс контейнера: состав без извлечения.

    ``format`` — ``"zip"``/``"7z"``/``"rar"``; ``solid`` — флаг сплошного блока из
    индекса, причём ``None`` означает «формат/бэкенд этого не сообщает» (zip несолиден
    **по построению** — для него ``False``, а не ``None``; RAR — ``None``, флаг в индексе
    не читается); ``encrypted`` — контейнер требует пароля (AES/ZipCrypto/7zAES/RAR-
    заголовок); ``truncated`` — листинг неполон (бэкенд оборвал индекс по своему
    внутреннему потолку); ``unreadable`` — человекочитаемая причина, если
    **листинг вообще не удался** (битый файл, нет бэкенда, нет внешней утилиты). При
    ``unreadable`` состав пуст, но поля ``format``/``solid`` остаются осмысленными.

    ``unreadable`` — не исключение и не тихий пустой список: потребитель обязан
    показать его как видимый пропуск спуска.
    """

    format: str
    members: tuple[ContainerMember, ...]
    solid: bool | None
    encrypted: bool
    truncated: bool
    unreadable: str | None


@runtime_checkable
class ContainerPort(Protocol):
    """Читатель контейнера: индекс отдельно, тела членов — потоком.

    Два инварианта, ради которых порт существует:

    (a) **листинг — не извлечение**: :meth:`list_members` читает только индекс
        контейнера и не распаковывает ни одного байта тела члена;
    (b) **``open_member`` стримит**: он отдаёт итератор чанков и не требует держать
        член (или архив) целиком в памяти.

    ``version`` — строка провенанса (``zipfile-3.14``, ``py7zr-1.1.4``,
    ``rarfile-4.5+unrar``); она входит в провенанс прогона, поэтому непуста и стабильна
    и при отсутствующем бэкенде (``py7zr-unavailable``). ``available()`` — честный
    предикат «можно ли сейчас прочитать контейнеры этого формата»: он **не** бросает
    исключений и учитывает **все** условия (пакет, внешняя утилита). Отсутствие бэкенда
    деградирует **видимо** — ``unreadable="backend_unavailable: ..."``, а не пустым
    листингом и не исключением.
    """

    version: str

    def available(self) -> bool:
        """Можно ли прочитать контейнеры этого формата прямо сейчас (без исключений)."""
        ...

    def list_members(self, path: str) -> ContainerListing:
        """Индекс контейнера по пути к файлу; ошибки — в ``unreadable``, не исключением."""
        ...

    def open_member(self, path: str, member_path: str) -> Iterator[bytes]:
        """Поток чанков тела члена (никогда — член целиком в памяти)."""
        ...
