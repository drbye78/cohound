"""Порт счётчика токенов — ``TokenCounterPort`` (O21 плана 26).

Зачем порт, а не готовая функция. Токены — свойство **конкретного** токенизатора: один и
тот же текст у двух моделей даёт разное число токенов. Значит число токенов — это условие
измерения, и его источник обязан быть объявленным входом (как ``embed_spec``), а не
константой в коде ограничителя. Порт называет **величину** и её провенанс; чем именно она
считается, решает адаптер и объявляет через :attr:`spec`.

**Единица измерения — токены содержимого.** ``len(token_ends(text))`` — сколько токенов
занимает **текст**, а не сколько токенов уйдёт в модель при вызове: служебные токены
(``<s>``/``</s>`` и подобные) модель добавляет сама, и в бюджет чанка они не входят.
Поэтому адаптер считает без служебных токенов, и два счётчика одной величины не
расходятся на постоянную добавку. Граница лимита считается ровно по этой величине.

**Символьный прокси запрещён (A3).** Отношение «токены на символ» зависит от языка и
алфавита; подставить его значило бы мерить другую величину под тем же именем — и объявить
в манифесте ограничение, которого не было. Нет токенизатора — нет ограничителя (видимый
отказ), а не оценка по длине строки.

**Почему концы токенов, а не число.** Ограничителю нужно **резать по границе токена**, а
не угадывать её по номеру символа: только так кусок остаётся точным срезом текста
(``doc.text[char_start:char_end] == text``) и одновременно не превышает лимит. Поэтому
порт отдаёт не длину, а позиции: ``token_ends[i]`` — исключающий конец ``i``-го токена в
**символах того же текста**.

**Монотонность и пустые отрезки.** ``token_ends`` покрывает текст слева направо:
``0 <= token_ends[0] <= token_ends[1] <= … <= len(text)``. Токен, не занимающий символов
(служебный, нулевой отрезок), даёт пустой отрезок; такие отрезки реализация **отбрасывает**,
чтобы ``len(token_ends(text))`` было числом токенов содержимого и чтобы граница реза,
взятая по концу токена, всегда двигала позицию. Отсюда следствие, на которое опирается
ограничитель: все отрезки строго возрастают.

Отдельного метода ``count`` у порта **нет**: два метода одной величины разъедутся (один
начнёт считать со служебными, другой без), и различить это будет нечем.

Нейтрален (§1.3): порт не знает ни одной модели по имени.
"""

