"""Сегментация CJK для лексического контура: биграммы внутри прогонов (без зависимостей).

Зачем это отдельный модуль. BM25-плечо режет текст по «слову»: ``Tokenizer.simple``
(tantivy) и ``_TOKEN_RE`` (in-process baseline) считают словом непрерывную серию
алфавитно-цифровых символов. Для китайского/японского/корейского текста, где пробелов и
пунктуации внутри фразы нет, вся серия — **один токен**: документ
«…数据库配置管理工具…» индексируется одним термом, и запрос «配置管理» (другой терм) не
находит ничего. Замер 03.11.2026 на реальной цепочке: 0 хитов на двух запросах, 1 на
английском контроле (``docs/reports/measurements/2026-11-04-cjk-lexical-segmentation.md``).

Приём — стандартный для BM25 без словаря и без новых зависимостей (ICU/jieba не входят
в стек: лицензии, вес, версионная связка): **биграммы символов** внутри прогонов Han,
хираганы, катаканы и хангыля. Прогон длиной 1 даёт один токен-символ; прогон длиной N
даёт N-1 перекрывающихся биграмм. Никакой морфологии и словаря: биграмма — единица
индекса, а не «слово», поэтому качество на живом ZH-корпусе остаётся открытым вопросом
(в пилотной когорте CJK-материала нет).

Чем это **не** является:

* не нормализация и не переписывание текста — ``segment_cjk`` только **вставляет
  пробелы** между термами для представления индекса; тело чанка, его ``content_hash`` и
  смещения (``char_start``/``char_end``) не меняются, потому что хранимый текст не
  трогается;
* не языковой детектор: границы прогонов заданы код-поинтами, а не вероятностью;
* не словарь: «数据库配置管理工具» режется на ``数据 据库 库配 配置 置管 管理 理工 工具``,
  включая бессмысленные пары. Для BM25 это шум, а не ошибка: лишние термы редки в
  корпусе и получают низкий IDF.

Границы прогонов — **пунктуация и пробелы**: ``。！？；，、：`` (CJK-пунктуация),
``・`` (катакана, U+30FB), полноширинные формы (U+FF00–U+FFEF), любые не-CJK символы.
Текст не нормализуется: полноширинная запятая остаётся собой и служит границей.

Инвариант, который держит совместимость с EN/RU: для текста без CJK
``segment_cjk(text)`` возвращает **тот же объект строки** (не «эквивалентную» сборку), а
``CJK_RANGES`` не пересекается ни с латиницей, ни с кириллицей. Поэтому список токенов
латиницы/кириллицы не меняется — это закреплено пином
``tests/util/test_text_utils.py::test_tokenize_lexical_without_cjk_is_byte_identical_to_legacy``.
"""

from __future__ import annotations

import re
from collections.abc import Iterator

__all__ = [
    "CJK_RANGES",
    "cjk_terms",
    "is_cjk_char",
    "iter_cjk_runs",
    "segment_cjk",
]

#: Прогоны CJK-письменностей (включительные диапазоны код-поинтов).
#:
#: Han — основная таблица, расширение A, совместимость и астровые расширения B–F
#: (U+20000…U+2FA1F: в Python 3 строки — код-поинты, суррогатов нет). Кана — хирагана и
#: катакана **без** комбинирующих знаков (U+3097–U+309C) и без ``・`` U+30FB: это
#: пунктуация, то есть граница прогона. Хангыль — слоги, чамо и их расширения.
#:
#: Полноширинные формы (U+FF00–U+FFEF), CJK-пунктуация (U+3000–U+303F) и цифры/латиница
#: в диапазоны не входят намеренно: они либо границы, либо обычная токенизация.
CJK_RANGES: tuple[tuple[int, int], ...] = (
    (0x3400, 0x4DBF),    # Han, расширение A
    (0x4E00, 0x9FFF),    # Han, основная таблица
    (0xF900, 0xFAFF),    # Han, совместимость
    (0x20000, 0x2FA1F),  # Han, расширения B–F + совместимость-дополнение
    (0x3041, 0x3096),    # хирагана
    (0x309D, 0x309F),    # хирагана, итерационные знаки
    (0x30A0, 0x30FA),    # катакана (U+30FB «・» — пунктуация, не входит)
    (0x30FC, 0x30FF),    # катакана: долгота и итерационные знаки
    (0x1100, 0x11FF),    # хангыль, чамо
    (0x3130, 0x318F),    # хангыль, совместимость
    (0xA960, 0xA97F),    # хангыль, чамо A
    (0xAC00, 0xD7AF),    # хангыль, слоги
    (0xD7B0, 0xD7FF),    # хангыль, чамо B
)


def _regex_atom(start: int, end: int) -> str:
    """Код-поинт в виде, который понимает ``re`` (``\\u`` для BMP, ``\\U`` для астровых)."""
    escape = "\\u{:04x}" if end <= 0xFFFF else "\\U{:08x}"
    return f"{escape.format(start)}-{escape.format(end)}"


_CJK_RUN_RE = re.compile("[" + "".join(_regex_atom(s, e) for s, e in CJK_RANGES) + "]+")


def is_cjk_char(char: str) -> bool:
    """Один символ принадлежит прогону CJK (Han/кана/хангыль)?"""
    if not char:
        return False
    codepoint = ord(char)
    return any(start <= codepoint <= end for start, end in CJK_RANGES)


def iter_cjk_runs(text: str) -> Iterator[tuple[int, int]]:
    """Смещения ``(start, end)`` максимальных прогонов CJK в тексте, слева направо.

    Прогон — непрерывная серия CJK-символов; пунктуация, пробелы, латиница и кириллица
    его разрывают. Пустая строка не даёт прогонов.
    """
    for match in _CJK_RUN_RE.finditer(text or ""):
        yield match.span()


def cjk_terms(run: str) -> list[str]:
    """Термы одного CJK-прогона: перекрывающиеся биграммы, для длины 1 — сам символ.

    Пустой прогон — пустой список. Порядок детерминирован (слева направо), поэтому
    одинаковый вход даёт одинаковый список токенов — это проверяется тестом, а не
    обещанием.
    """
    if not run:
        return []
    if len(run) == 1:
        return [run]
    return [run[index : index + 2] for index in range(len(run) - 1)]


def segment_cjk(text: str) -> str:
    """Представление текста для лексического индекса: CJK-прогоны → термы через пробел.

    Вставляет по пробелу вокруг каждого прогона и между его термами; **все остальные
    символы копируются как есть**, в исходном порядке. Текст без CJK возвращается тем же
    объектом строки — на этом держится побайтовая неизменность EN/RU-токенизации.

    Зачем пробелы, а не замена: ``Tokenizer.simple`` (tantivy) и ``_TOKEN_RE``
    (in-process BM25) видят пробел как готовую границу токена, поэтому одна и та же
    функция обслуживает оба плеча, а стеммеры/стоп-слова продолжают работать на
    латинице/кириллице без изменений.

    Плата названа явно: это **представление индекса**, а не хранимый текст. Позиции
    термов внутри CJK-прогона синтетические (биграммы перекрываются), поэтому запрос
    фразы по CJK опирается на порядок биграмм, а не на исходные смещения символов.
    """
    if not text:
        return text
    parts: list[str] = []
    position = 0
    for start, end in iter_cjk_runs(text):
        parts.append(text[position:start])
        parts.append(" ")
        parts.append(" ".join(cjk_terms(text[start:end])))
        parts.append(" ")
        position = end
    if not parts:
        return text
    parts.append(text[position:])
    return "".join(parts)