"""Размыкатель сети: пауза вместо «молча превратить прогон в провалы».

**Зачем.** Фетч-слой уже повторяет транзиентный отказ (``core/util/fetch_retry.py``), но
у повтора есть свой предел: если канал пропал целиком (отключили сеть, лёг VPN, сломался
DNS), каждая волна честно исполнит свои две попытки, получит «ответа не было» и запишет
элемент сбоем. Прогон при этом не падает — он **тихо** превращает всю оставшуюся когорту
в провалы, а «мы не смотрели» и «посмотрели и не нашли» — разные факты (I2d): из сбоя
транспорта нельзя выводить отсутствие возможности у продукта.

**Что считается отказом канала, а что нет.** Считаются только исходы, где **ответа не
было вовсе**: таймаут, обрыв соединения, неразрешённое имя. HTTP-ответ ``5xx`` сюда НЕ
входит: сервер ответил — значит канал работает, а болен один хост, и размыкать из-за него
сеть значило бы остановить когорту из-за чужой аварии. ``4xx``/``5xx``/``304`` — это
наблюдения о канале, поэтому они его серию **сбрасывают** (см. :meth:`note_response`).
Классификацию даёт вызывающий: ``util`` не импортирует ``ports`` (матрица слоёв §1.3),
поэтому машина получает готовый вердикт «ответа не было» и сама исключений не разбирает.

**Почему нужны РАЗНЫЕ хосты.** Пять таймаутов подряд на одном хосте — свойство хоста
(он лежит, его режут по IP, у него свой таймаут), а не канала; пауза тут ничего не лечит,
а только откладывает работу. Канал — это то, что проявляется **поперёк** хостов, поэтому
размыкание требует одновременно ``consecutive >= threshold`` И
``len(distinct_hosts) >= min_hosts``.

**Почему пауза, а не отказ прогона.** Отказ прогона (исключение) уничтожил бы уже
добытое и заставил бы перезапускать всё; пауза оставляет необработанное ``pending`` —
durable-факт «не смотрели» сохраняется, и следующий проход продолжит с того же места.
Срабатывание даёт **одну** паузу: после неё счётчики обнуляются, иначе однажды
разомкнувшись, машина не дала бы продолжить.

**Пауза и продолжение — буквально.** Первая пауза отвечает на вопрос «это блип или канал
умер?»: для моргающего канала (переключение wifi, обрыв VPN на полминуты) остановка была бы
хуже самой аварии — двадцатисекундный блип превратился бы в брошенную когорту, которую надо
возобновлять вручную. Поэтому после паузы прогон **продолжается**. Если канал не ожил,
отказы соберутся снова, и **вторая** серия подряд означает, что пауза не помогла:
:attr:`NetworkBreaker.exhausted` становится ``True``, остаток честно остаётся ``pending``, а
сеанс финализируется с названной причиной. Число пауз — ``BreakerPolicy.max_trips``
(видно в политике и в провенансе), а не спрятанная в ветке константа.

**Часов здесь нет.** Машина чистая: без ``sleep``, без времени, без I/O и без глобального
состояния. Паузу исполняет вызывающий, поэтому поведение проверяется без ожидания.

**Не входит в контракт.** Размыкатель — **исполнение**, а не условие измерения: его
порог, число хостов и длительность паузы не меняют ``run_id`` и не входят в
``EXECUTION_CONTRACT_FIELDS``. Он не меняет и вердиктов: необработанное остаётся
``pending``, а не становится ``failed``.

Нейтрален (§1.3): только stdlib и целые числа.
"""

from __future__ import annotations

from dataclasses import dataclass

__all__ = ["BreakerPolicy", "BreakerTrip", "NetworkBreaker"]


@dataclass(frozen=True)
class BreakerPolicy:
    """Порог размыкания: сколько отказов на скольких хостах, на сколько пауза, сколько раз.

    :param threshold: сколько **подряд** идущих отказов «ответа не было» требуется.
    :param min_hosts: на скольких **разных** хостах они обязаны случиться (свойство
        канала, а не одного больного хоста).
    :param pause_s: длительность паузы, секунды. Машина её только **объявляет**
        (:attr:`NetworkBreaker.pending_pause_s`); спит вызывающий.
    :param max_trips: сколько срабатываний прогон выдерживает, прежде чем признать канал
        мёртвым. Первая пауза отвечает на вопрос «это блип или канал умер?» — после неё
        прогон **продолжается**. Вторая серия отказов подряд означает, что пауза не
        помогла, и продолжать бессмысленно: остаток честно остаётся ``pending``, а сеанс
        финализируется с названной причиной. Это не «потолок ради безопасности», а
        число, отвечающее на конкретный вопрос, — и оно видно в политике и в провенансе
        (``max_trips``/``trips``), а не спрятано в коде ветки.
    """

    threshold: int = 5
    min_hosts: int = 2
    pause_s: float = 60.0
    max_trips: int = 2

    def __post_init__(self) -> None:
        for name, value in (
            ("threshold", self.threshold),
            ("min_hosts", self.min_hosts),
            ("max_trips", self.max_trips),
        ):
            # ``bool`` — подкласс ``int``, но «True хоста» не значение порога.
            if isinstance(value, bool) or not isinstance(value, int) or value <= 0:
                raise ValueError(f"BreakerPolicy.{name}: ожидалось целое > 0, дано {value!r}")
        if not isinstance(self.pause_s, (int, float)) or isinstance(self.pause_s, bool):
            raise ValueError(
                f"BreakerPolicy.pause_s: ожидалось число > 0, дано {self.pause_s!r}"
            )
        if not self.pause_s > 0:
            raise ValueError(
                f"BreakerPolicy.pause_s: ожидалось число > 0, дано {self.pause_s!r}"
            )


@dataclass(frozen=True)
class BreakerTrip:
    """Срабатывание: провенанс одной паузы (сколько, на чём, на сколько).

    Нужен потому, что после срабатывания счётчики обнуляются: иначе вызывающий не смог
    бы назвать в записи, **что** именно его разомкнуло, и запись стала бы бесполезной.

    :param consecutive: сколько отказов без ответа шло подряд на момент срабатывания.
    :param hosts: хосты, на которых они случились (отсортированы — запись детерминирована).
    :param pause_s: объявленная длительность паузы, секунды.
    """

    consecutive: int
    hosts: tuple[str, ...]
    pause_s: float


class NetworkBreaker:
    """Счётчик серии «ответа не было»: размыкает сеть по правилу :class:`BreakerPolicy`.

    Состояние — три поля (серия, множество хостов серии, число срабатываний). Ни часов,
    ни блокировок: машину ведёт **один** поток (в драйвере когорты — главный поток
    драйвера, где исходы волн и собираются: состояние пула процессов не разделяется,
    общий счётчик в воркерах был бы ложью).
    """

    def __init__(self, policy: BreakerPolicy | None = None) -> None:
        self._policy = policy if policy is not None else BreakerPolicy()
        self._consecutive = 0
        self._hosts: set[str] = set()
        self._trips = 0
        self._last_trip: BreakerTrip | None = None
        self._pause_s = 0.0

    @property
    def policy(self) -> BreakerPolicy:
        """Действующая политика (объявленный вход, а не вывод из наблюдений)."""
        return self._policy

    @property
    def trips(self) -> int:
        """Сколько раз машина размыкалась за жизнь объекта (провенанс прогона)."""
        return self._trips

    @property
    def last_trip(self) -> BreakerTrip | None:
        """Провенанс последнего срабатывания (``None`` — не размыкалась)."""
        return self._last_trip

    @property
    def consecutive(self) -> int:
        """Длина текущей серии отказов «ответа не было»."""
        return self._consecutive

    @property
    def distinct_hosts(self) -> int:
        """Сколько разных хостов в текущей серии."""
        return len(self._hosts)

    @property
    def exhausted(self) -> bool:
        """Паузы исчерпаны: канал не ожил после ``max_trips`` срабатываний.

        ``True`` — продолжать бессмысленно: следующая серия отказов всё равно упрётся в
        тот же мёртвый канал. Вызывающий в этом случае не выдаёт работу, а остаток честно
        оставляет ``pending`` (факт «не смотрели», а не ``failed``).
        """
        return self._trips >= self._policy.max_trips

    @property
    def pending_pause_s(self) -> float:
        """Объявленная пауза, пока канал не подал признак жизни, иначе ``0.0``.

        Пауза считается снятой **ответом** (:meth:`note_response`): до него канал
        остаётся разомкнутым, и вызывающий обязан считать паузу действующей. Свойство
        ничего не потребляет и не меняет — читать его можно сколько угодно раз.
        """
        return self._pause_s

    def note_response(self) -> None:
        """Получен **любой** ответ (включая ``4xx``/``5xx``) — канал жив, серия сброшена.

        Сбрасываются и счётчик серии, и множество хостов: серия — это «подряд идущие
        отказы», и ответ её прерывает. ``5xx`` сюда попадает намеренно: сервер ответил,
        значит проблема в нём, а не в канале.
        """
        self._consecutive = 0
        self._hosts.clear()
        self._pause_s = 0.0

    def note_silence(self, host: str) -> bool:
        """Отказ без ответа на ``host``; ``True`` — ровно в момент размыкания.

        Возврат ``True`` означает переход в разомкнутое состояние: вызывающий объявляет
        паузу. Что делать дальше — его решение по :attr:`exhausted`: не исчерпано —
        продолжить после паузы (канал мог ожить), исчерпано — прекратить выдачу работы.
        Счётчики при этом обнуляются, чтобы следующая серия считалась заново, — иначе
        после первого размыкания машина молчала бы навсегда.

        :param host: origin отказа (тот же ключ, что у пейсинга). Пустой недопустим:
            «отказ неизвестно где» не доказывает свойство канала, и тихо принять его за
            отдельный хост значило бы размыкать сеть по выдуманному факту.
        """
        normalized = (host or "").strip().lower()
        if not normalized:
            raise ValueError("NetworkBreaker.note_silence: пустой host")
        self._consecutive += 1
        self._hosts.add(normalized)
        policy = self._policy
        if self._consecutive < policy.threshold or len(self._hosts) < policy.min_hosts:
            return False
        self._trips += 1
        self._last_trip = BreakerTrip(
            consecutive=self._consecutive,
            hosts=tuple(sorted(self._hosts)),
            pause_s=policy.pause_s,
        )
        self._pause_s = policy.pause_s
        self._consecutive = 0
        self._hosts.clear()
        return True
