"""coHound — операционный рычаг памяти: возврат свободных арен glibc ОС (только stdlib).

**Зачем это здесь.** Экстракция документов (docling/torch) держит рабочий набор, который
Python не отдаёт ОС: освобождённые блоки остаются в аренах glibc, и RSS процесса растёт
храповиком, пока OOM-killer не вмешается. Замер 22.10 на этом хосте (6.9 GB, **один**
процесс, ``document_level: layout_tables``):

=========================================  ==============
стадия                                     RSS
=========================================  ==============
голый python                               14 MB
``import torch``                           231 MB
``import core.adapters.extract_document``  403 MB
после первого PDF (9 стр.) — веса в RAM    1317 MB
после PDF на 81 стр.                       1679 MB (пик 2609 MB)
ещё 4 мелких PDF, **без** trim             2052 MB
``malloc_trim(0)``                         1679 → 1084 MB
``malloc_trim(0)`` (второй, позже)         1406 → 1240 MB
=========================================  ==============

То есть «пол» резидента — ~1.1 GB на воркер (torch 231 MB + docling-импорты 172 MB +
веса моделей ~500 MB на диске + одна страница в полёте), а всё выше — арены аллокатора,
а не объективная потребность. :func:`release_free_arenas` возвращает их ОС.

**Строка ``import core.adapters.extract_document`` (403 MB) — исторический замер.** С
22.10 docling в адаптере импортируется лениво (при первом извлечении документа, а не при
импорте модуля): сейчас ``import core.adapters.extract_document`` ≈38 MB, ``import
core.cli.wiring`` — 77 MB вместо 426 MB. «Пол» воркера, которому **достался** PDF, тот же
(веса и арены никуда не делись); изменилось лишь то, что HTML-воркеры за него больше не
платят.

Повторный замер из этого модуля (тот же хост, два реальных PDF 7 и 9 стр.): 14 → 231 →
403 MB на импортах, 1401 MB после первого, 1480 MB после второго (пик 1715 MB), и
``malloc_trim(0)`` дал **1480 → 1122 MB** (≈360 MB ОС, возврат ``1``). Цифры брифа
воспроизводятся: рычаг работает, «пол» тот же.

**Это операционный рычаг, а не корректность.** Функция не меняет ни одного наблюдаемого
значения: текст, хеши, чанки, статусы, счётчики — те же. Поэтому она **не** входит в
``EXECUTION_CONTRACT_FIELDS``, **не** меняет ``run_id`` и **не** требует
``execution_change`` (§13): это гигиена памяти процесса, а не условие измерения. По той же
причине у неё нет конфигурационной оси — ось краула попала бы в ``CrawlLimits.as_dict()``
→ ``crawl_config_digest`` → контракт → новый ``run_id``, а рычаг памяти не вправе ветвить
идентичность прогона.

**Границы.** ``malloc_trim`` — расширение GNU libc: в системах без glibc, при
отсутствии ``libc.so.6``/символа и при любой ошибке — безопасный no-op, возвращающий
``False``. Сколько байт реально отдано, стандарт не сообщает (``malloc_trim`` возвращает
лишь признак «trim выполнен»), поэтому наблюдаемость — счётчики вызовов/успехов
(:func:`trim_stats`), а не байты.
"""

from __future__ import annotations

import ctypes
from collections.abc import Callable

__all__ = ["release_free_arenas", "trim_stats"]

#: Сигнатура ``malloc_trim``: ``int malloc_trim(size_t pad)``.
_MallocTrim = Callable[[int], int]

#: Разрешённая ссылка на ``malloc_trim`` (``None`` — библиотека/символ недоступны).
#: Кэшируется на процесс: ``CDLL``/``dlsym`` — не то, что стоит делать на каждый документ.
_TRIM_FN: _MallocTrim | None = None
#: Разрешение уже выполнено (в т.ч. неудачно) — повторных ``CDLL`` нет.
_RESOLVED = False

#: Счётчики **этого** процесса (в воркер-процессе — его собственные).
_CALLS = 0
_RELEASED = 0


def _load_malloc_trim() -> _MallocTrim | None:
    """Берёт ``malloc_trim`` из ``libc.so.6``; ``None`` — не glibc или нет символа.

    Единственное место, знающее о ``ctypes``/libc. Ошибка загрузки — не сбой прогона:
    рычаг памяти отсутствует, извлечение работает как прежде.
    """
    try:
        libc = ctypes.CDLL("libc.so.6")
        fn = libc.malloc_trim
        fn.argtypes = [ctypes.c_size_t]
        fn.restype = ctypes.c_int
    except Exception:  # noqa: BLE001 — система без glibc: рычага нет, это не ошибка
        return None
    return fn


def _malloc_trim() -> _MallocTrim | None:
    """Ссылка на ``malloc_trim``, разрешаемая ровно один раз за процесс."""
    global _TRIM_FN, _RESOLVED
    if not _RESOLVED:
        _TRIM_FN = _load_malloc_trim()
        _RESOLVED = True
    return _TRIM_FN


def release_free_arenas() -> bool:
    """Отдаёт ОС свободные арены glibc (``malloc_trim(0)``); ``True`` — trim выполнен.

    ``True`` — libc сообщил, что trim произошёл (``malloc_trim`` вернул 1). Это **не**
    объём и не гарантия, что RSS уменьшился: на замере первый вызов дал 1480 → 1122 MB,
    а второй подряд вернул ``1`` при неизменном RSS (отдавать уже было нечего). Сколько
    именно байт вернулось ОС, libc не сообщает — поэтому наблюдаемость считает вызовы,
    а не байты.

    ``False`` — либо нечего было отдавать (libc вернул 0), либо система без glibc, либо
    вызов не удался; во всех случаях это не ошибка и не повод менять поведение
    вызывающего.

    Функция **никогда не поднимает исключений** и не имеет побочных эффектов, кроме
    счётчиков :func:`trim_stats`: она вызывается в воркер-процессе на каждый документ,
    где сбой гигиены памяти не должен стоить извлечения.
    """
    global _CALLS, _RELEASED
    _CALLS += 1
    fn = _malloc_trim()
    if fn is None:
        return False
    try:
        released = int(fn(0)) != 0
    except Exception:  # noqa: BLE001 — вызов не вправе ломать вызывающего
        return False
    if released:
        _RELEASED += 1
    return released


def trim_stats() -> dict[str, int]:
    """Счётчики trim **этого** процесса: ``calls`` (все вызовы) и ``released`` (успехи).

    Счётчик процесса-воркера родителю не виден (обратного канала из воркера нет), поэтому
    операторская видимость рычага — строка фазы корпуса (``core/pipeline/corpus.py``),
    а этот словарь — для диагностики в самом процессе и для тестов.
    """
    return {"calls": _CALLS, "released": _RELEASED}
