"""coHound — малые **точные** статистики для приборов (без scipy и без приближений).

Зачем отдельный модуль. Точный двусторонний критерий МакНемара был скопирован в четыре
прибора (``scripts/measure_query_lang.py``, ``measure_embed_input_variant.py``,
``measure_token_limit_retrieval.py``, ``measure_cross_lingual_retrieval.py``). Копии
совпадали, но каждая была отдельной возможностью разойтись в округлении — а число,
посчитанное двумя формулами под одним именем, читатель не отличит от настоящего
расхождения приборов. Формула одна, значит и место у неё одно; остальные приборы могут
перейти на неё, когда их будут править по другому поводу.

Почему **точный**, а не ``chi2``: на парных сравнениях ретривала дискордантных пар
десятки, а не сотни, и асимптотика хи-квадрат даёт на них заниженный ``p``. При
``better + worse == 0`` настройки на этих данных неразличимы — это ``1.0``, а не ноль.

Нейтрален к предметной категории (§1.3): чисел о продуктах здесь нет.
"""

from __future__ import annotations

from math import comb

__all__ = ["mcnemar_exact_p"]


def mcnemar_exact_p(better: int, worse: int) -> float:
    """Точный двусторонний критерий МакНемара на дискордантных парах.

    :param better: сколько ячеек первая настройка выиграла, а вторая проиграла.
    :param worse: сколько наоборот.
    :returns: ``p`` в ``[0, 1]``; ``1.0``, когда дискордантных пар нет.

    Согласованные пары (обе настройки попали / обе промахнулись) в критерий **не** входят:
    они не различают настройки, и включение их раздуло бы «значимость» числом лёгких
    ячеек. Считается хвост биномиального распределения при ``p = 0.5``, удвоенный
    (двусторонний), с отсечкой на единице.
    """
    if better < 0 or worse < 0:
        raise ValueError(f"МакНемар: счётчики неотрицательны, получено {better}/{worse}")
    total = better + worse
    if total <= 0:
        return 1.0
    tail = sum(comb(total, i) for i in range(0, min(better, worse) + 1))
    return min(1.0, 2 * tail / (2**total))
