"""Состав входа эмбеддера: какая строка чанка уходит в модель (O19).

**Зачем отдельный модуль.** Состав входа — условие измерения: он входит в
``chunking_spec`` и через него в ``run_id``. Живёт он здесь, а не в адаптере чанкера,
потому что читают его **двое**: сборщик партиции (``core.pipeline.corpus_index``, слой
``pipeline``) и объявление геометрии нарезки (``core.adapters.chunker_family``, слой
``adapters``). Пока константа лежала в адаптере, у ``pipeline`` не было способа её
исполнить, не нарушив матрицу зависимостей (§4.1): ``pipeline → adapters`` запрещено, и
это ровно тот случай, когда нарушение было бы не косметическим — исполнение зависело бы от
слоя, которому запрещено исполнять.

**Почему объявленный состав должен исполняться.** До 16.11.2026
:data:`EMBED_INPUT_FIELDS` был **мёртвым объявлением**: контракт называл состав входа,
которого исполнение не имело (тот же класс дефекта, что ``pool_multiplier`` и
``cross_query_fusion`` до O12/O13). Теперь строка собирается здесь, поэтому объявленное и
исполненное — одно и то же по построению, а не по договорённости.

Нейтрален (§1.3): ни продуктов, ни домена — только имена полей чанка.
"""

from __future__ import annotations

from typing import Any, Protocol

__all__ = ["EMBED_INPUT_FIELDS", "embed_input_text"]

#: Из каких полей чанка собирается текст, уходящий в эмбеддер. Часть **условия
#: измерения**, а не деталь реализации: смена состава меняет индекс, не меняя версию
#: правил нарезки, поэтому она обязана попадать в ``run_id`` через
#: :func:`~core.adapters.chunker_family.composite_chunking_spec`. Сегодня — только
#: ``text`` (``context_prefix`` генерируется и хранится, но в эмбеддинг не входит).
EMBED_INPUT_FIELDS: tuple[str, ...] = ("text",)

#: Разделитель полей входа эмбеддера. Два перевода строки — граница, которой в тексте
#: чанка не бывает «случайно»: склейка остаётся однозначной, а не зависит от того, чем
#: кончился предыдущий фрагмент.
_EMBED_INPUT_SEP = "\n\n"


class _HasFields(Protocol):
    """Минимум, который нужен сборщику строки: поля чанка по имени."""


def embed_input_text(chunk: Any) -> str:
    """Строка, которая уходит в эмбеддер: объявленные поля в объявленном порядке.

    **Почему это функция, а не ``chunk.text``.** :data:`EMBED_INPUT_FIELDS` входит в
    ``chunking_spec``, то есть в ``run_id``, и до этой правки **не исполнялась**: контракт
    называл состав входа, которого исполнение не имело. Теперь состав читается здесь,
    поэтому объявленное и исполненное — одно и то же по построению.

    Пустые поля **пропускаются**: чанк без заголовка даёт ровно ``text``, а не текст с
    пустым префиксом. Иначе вектор зависел бы от наличия пустой строки, а не от содержания.

    При составе ``("text",)`` результат **байт-в-байт** равен ``chunk.text``: это то
    свойство, на котором держится неизменность ``embed_cache`` и дедупа при выключенной оси.
    """
    parts: list[str] = []
    for field in EMBED_INPUT_FIELDS:
        value = getattr(chunk, field, None)
        if value is None:
            continue
        text = str(value)
        if not text.strip():
            continue
        parts.append(text)
    return _EMBED_INPUT_SEP.join(parts)
