"""Pytest-фикстуры: корень репозитория на sys.path (плоская раскладка, §3.3).

**Изоляция межпрогонных кэшей.** ``resolve_paths()`` без ``COHOUND_HOME``/``paths.yaml``
отдаёт CWD-относительные дефолты, поэтому кэши Ф1.2/Ф3 (``extract_cache/``,
``eval_cache/``) без этой фикстуры попадали бы в корень репозитория — общий каталог на
все прогоны процесса. Это делало набор тестов **неидемпотентным**: первый прогон
наполнял кэш, второй получал хит и падал на утверждениях вида «оценщик вызван».
Кэш обязан переживать прогоны (в этом его смысл) — значит изолировать его должны
тесты, а не боевой код. Сессионный временный каталог даёт ровно это: внутри сессии
кэш общий (как в бою), между сессиями — пустой.
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

#: Тесты не должны зависеть от операторского ``./.env``: CLI загружает dotenv на входе
#: (03 §D.6), и файл разработчика иначе менял бы поведение ``main()``-тестов. Тесты,
#: которым нужна автозагрузка, снимают этот opt-out через ``monkeypatch.delenv``.
os.environ.setdefault("COHOUND_NO_DOTENV", "1")

#: F0: бюджет памяти экстракции **объявляется** тестам, а не измеряется у хоста.
#:
#: Без явного бюджета :func:`core.pipeline.resources.resolve_mem_budget_mb` берёт
#: ``MemAvailable`` минус резерв, а preflight §3.3 превращает «0 воркеров» в отказ
#: ``EXIT_USAGE``. Тогда **старт** прогона зависел бы от соседних процессов и от
#: параллельности pytest: на занятом хосте бюджет падает ниже пика ``full`` (4833 MB +
#: 500 MB пола), и прогон отказывал бы даже там, где документной экстракции нет вовсе
#: (тестовые краулеры/экстракторы подменены). Тест, который не проверяет бюджет, обязан
#: видеть бюджет постоянным — ровно так же, как его видит оператор, объявивший число.
#:
#: Значение — ``PARENT_FLOOR_MB + DOCLING_PEAK_MB[full]`` = 5333 MB: помещается **ровно
#: один** воркер, поэтому окно выводится как ``1`` и экстракция остаётся inline-путём
#: (пул не создаётся) — поведение тестов не меняется, а старт перестаёт зависеть от
#: памяти хоста. Тесты самой арифметики бюджета снимают значение через
#: ``monkeypatch.delenv``/``setenv`` и передают своё.
os.environ.setdefault("COHOUND_MEM_BUDGET_MB", "5333")

#: Env-переменные каталогов межпрогонных кэшей (см. ``core/config/paths.py``).
_CACHE_ENV = ("COHOUND_EXTRACT_CACHE_DIR", "COHOUND_EVAL_CACHE_DIR")


@pytest.fixture(scope="session", autouse=True)
def _isolated_operational_caches(tmp_path_factory: pytest.TempPathFactory) -> None:
    """Уводит межпрогонные кэши из корня репозитория во временный каталог сессии.

    ``autouse`` и ``session``: кэш общий для всех тестов сессии (так проверяется
    переиспользование), но не переживает её — иначе состояние протекает между
    запусками ``pytest`` и вердикты из предыдущего прогона обслуживают следующий.
    """
    root = tmp_path_factory.mktemp("operational_caches")
    for index, name in enumerate(_CACHE_ENV):
        os.environ[name] = str(root / f"cache{index}")


@pytest.fixture
def isolated_state_dir(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> Path:
    """Изолированный ``COHOUND_STATE_DIR`` — по одному на тест (09 §4.4).

    ``state/{package_id}/`` — точка ресурса **пакета**, и с файловым локом пакета она
    эксклюзивна: второй писатель того же пакета получает отказ, а не делит файл. Тесты
    подменяют пакет временным каталогом, но имя пакета у них общее (``package``), а
    ``state`` без ``COHOUND_HOME`` CWD-относителен — значит все тесты и все xdist-воркеры
    делили ``<repo>/state/package/`` и честно упирались в лок друг друга. Изоляция —
    обязанность тестов: каталог состояния один на пакет по построению, и «общий на весь
    набор» сделал бы его узким местом набора, а не проверкой.

    Не ``autouse``: модули, которые сами утверждают раскладку (``COHOUND_HOME`` и
    ``home/state``), подключают его явно — иначе фикстура подменила бы предмет проверки.
    """
    root = tmp_path / "state"
    monkeypatch.setenv("COHOUND_STATE_DIR", str(root))
    return root
