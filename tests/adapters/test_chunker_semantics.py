"""Property-тесты **семантической** смежности markdown-чанкера (план 26, O9).

Структурная смежность уже покрыта ``tests/adapters/test_chunker_markdown.py``: чанк не
рвёт минимальную единицу (строку таблицы, пункт списка, fence), несёт ``heading_path``,
контекст продолжения. Здесь проверяется другое — **смысловые связи между блоками**,
которые структурно независимы, но читаются только вместе:

1. вводная строка списка и его элементы — одно утверждение;
2. блок «Ограничения» принадлежит разделу, который он ограничивает;
3. примечание несёт **свой** объект, а не соседний;
4. отрицание остаётся рядом с предметом («X не поддерживает Y»);
5. таблица несёт свою шапку.

**Ограничение, названное прямо.** Это защита от регрессий, а **не** измерение качества
нарезки: тесты пинят конкретные случаи, а не оценивают, хороша ли нарезка на корпусе
(измерение — O19 плана 26). Совпадение всех пяти свойств не означает, что чанкер режет
хорошо; нарушение любого означает, что смысл искажён.

**Красные тесты — находка, а не разрешение чинить чанкер.** O9 не меняет нарезку: это
``execution_change`` (новый chunk-set ⇒ новый ``run_id``), который требует замера (T1).
Поэтому свойства, нарушенные текущим кодом, помечены ``xfail(strict=True)``: они падают
на нынешнем поведении и станут ``XPASS`` (то есть провалом) ровно тогда, когда нарезка
изменится, — это и заставит пересмотреть пины вместе с замером, а не молча.

Замер 09.11.2026 на текущем ``policy-5``: нарушены свойства 1–4 (вводная строка списка,
блок «Ограничения», примечание, отрицание) — разрез встаёт на структурной границе блока и
разлучает его с тем, к чему блок относится. Свойство 5 (шапка таблицы) выполняется:
продолжение несёт шапку в ``context_prefix``, и промпт её печатает. Причина у четырёх
нарушений одна: политика предпочитает **структурную** границу (начало следующего блока)
любой другой, не спрашивая, связаны ли блоки по смыслу; семантики «вводная строка ↔
список», «примечание ↔ объект», «отрицание ↔ предмет» у чанкера нет вовсе.

Нейтрален (§1.3).
"""

from __future__ import annotations

import pytest

from core.adapters.chunker_markdown import MarkdownChunker
from core.ports.types import Chunk


def _chunk(md: str, **kwargs: int) -> list[Chunk]:
    """Режет документ чанкером; ``min_chunk_size`` снят — тесты про смысл, не про порог."""
    kwargs.setdefault("min_chunk_size", 1)
    return MarkdownChunker(**kwargs).chunk_text("doc", md)


def _chunk_with(chunks: list[Chunk], needle: str) -> Chunk:
    """Единственный чанк, содержащий ``needle`` (иначе — провал с составом чанков)."""
    found = [chunk for chunk in chunks if needle in chunk.text]
    assert len(found) == 1, f"ожидался ровно один чанк с {needle!r}: {[c.text for c in chunks]}"
    return found[0]


def _assert_joined(chunks: list[Chunk]) -> None:
    """Страховка: свойство проверяется на полной нарезке, текст не потерян (P1)."""
    assert "".join(chunk.text for chunk in chunks)


#: Причина ``xfail``: свойство нарушено **текущей** нарезкой, а не забыто тестом.
#: ``strict=True`` делает будущее исправление видимым провалом (``XPASS``), поэтому
#: смена границ не пройдёт молча: она обязана прийти вместе с замером (T1).
_DEFECT = (
    "O9 плана 26: текущая нарезка нарушает свойство; исправление меняет chunk-set, "
    "то есть это execution_change и требует замера (T1), а не правки в O9"
)


# --------------------------------------------------------------------------- #
# 1. Вводная строка списка
# --------------------------------------------------------------------------- #


@pytest.mark.xfail(strict=True, reason=_DEFECT)
def test_list_intro_line_stays_with_its_items() -> None:
    """Вводная строка списка не отрывается от своих элементов.

    Предотвращаемое искажение: «Возможности:» остаётся в чанке с предыдущим абзацем, а
    сами возможности — в следующем. Второй чанк читается как голый перечень без
    утверждения, к чему он относится; первый — как обещание, за которым ничего нет.
    """
    md = (
        "# Возможности\n\n"
        "Продукт предоставляет набор функций, которые описаны ниже в этом разделе.\n\n"
        "Возможности:\n\n"
        "- резервное копирование;\n"
        "- потоковая репликация;\n"
        "- мониторинг запросов;\n"
    )
    # Разрез ставится ровно на границе списка: так его выбирает политика, когда окно
    # заканчивается сразу за первым пунктом.
    list_start = md.index("- резервное копирование")
    chunks = _chunk(md, chunk_size=list_start + 2)
    _assert_joined(chunks)

    intro = _chunk_with(chunks, "Возможности:")
    assert "- резервное копирование" in intro.text, (
        "вводная строка списка оторвана от элементов: "
        f"{[chunk.text for chunk in chunks]}"
    )


# --------------------------------------------------------------------------- #
# 2. Блок «Ограничения»
# --------------------------------------------------------------------------- #


@pytest.mark.xfail(strict=True, reason=_DEFECT)
def test_limitations_block_stays_with_its_section_statement() -> None:
    """Блок «Ограничения» не отрывается от раздела, которому принадлежит.

    Предотвращаемое искажение: перечень ограничений попадает в чанк без утверждения,
    которое он ограничивает. Ограничения читаются как самостоятельный факт (или, хуже,
    как ограничения соседнего объекта), хотя относятся к описанному выше продукту.
    """
    md = (
        "# Хранилище\n\n"
        "Продукт хранит данные в кластере из нескольких узлов и переключает ведущий узел "
        "автоматически.\n\n"
        "Ограничения:\n\n"
        "- только Linux;\n"
        "- не более 64 ядер;\n"
        "- без поддержки Windows;\n"
    )
    # Разрез встаёт на границе блока «Ограничения»: ровно так его выбирает политика,
    # когда окно заканчивается внутри этого блока.
    label_start = md.index("Ограничения:")
    chunks = _chunk(md, chunk_size=label_start + 2)
    _assert_joined(chunks)

    limitations = _chunk_with(chunks, "Ограничения:")
    assert "кластере из нескольких узлов" in limitations.text, (
        "блок ограничений оторван от раздела, который он ограничивает: "
        f"{[chunk.text for chunk in chunks]}"
    )


# --------------------------------------------------------------------------- #
# 3. Примечание и его объект
# --------------------------------------------------------------------------- #


@pytest.mark.xfail(strict=True, reason=_DEFECT)
def test_note_keeps_its_own_object() -> None:
    """Примечание (``Note``/``Примечание``) несёт свой объект, а не соседний.

    Предотвращаемое искажение: примечание к объекту А оказывается в чанке вместе с
    описанием объекта Б. Читатель относит оговорку к Б — то есть получает неверное
    утверждение о Б, которого в источнике нет.
    """
    md = (
        "# Объект А\n\n"
        "Объект А поддерживает потоковую репликацию и работает в кластере из нескольких "
        "узлов, причём переключение выполняется автоматически при отказе ведущего узла.\n\n"
        "> **Примечание.** Относится только к объекту А.\n\n"
        "Объект Б работает в одиночном режиме без репликации и без кластера вообще.\n"
    )
    note_start = md.index("> **Примечание")
    chunks = _chunk(md, chunk_size=note_start + 2)
    _assert_joined(chunks)

    note = _chunk_with(chunks, "Примечание")
    assert "поддерживает потоковую репликацию" in note.text, (
        f"примечание оторвано от своего объекта: {note.text!r}"
    )
    assert "одиночном режиме" not in note.text, (
        f"примечание приклеено к чужому объекту: {note.text!r}"
    )


# --------------------------------------------------------------------------- #
# 4. Отрицание и его предмет
# --------------------------------------------------------------------------- #


@pytest.mark.xfail(strict=True, reason=_DEFECT)
def test_negation_stays_with_its_object() -> None:
    """Отрицание не отрывается от предмета.

    Предотвращаемое искажение: разрез встаёт между «не» и глаголом. Чанк, начинающийся
    с «поддерживает потоковую репликацию», утверждает **обратное** источнику; отрицание
    осталось в предыдущем чанке и до читателя этого чанка не доходит.
    """
    prefix = ("продукт проверен на платформах и в конфигурациях "
              "и в разных сетевых условиях ")
    md = (
        prefix
        + "не поддерживает потоковую репликацию в этой конфигурации, и это важно "
        "учитывать при планировании внедрения системы в промышленную эксплуатацию."
    )
    negation = md.index("не поддерживает")
    chunks = _chunk(md, chunk_size=negation + len("не") + 1)
    _assert_joined(chunks)

    for chunk in chunks:
        if "поддерживает" in chunk.text:
            before = chunk.text[: chunk.text.index("поддерживает")]
            assert "не" in before.split(), (
                "чанк утверждает положительное там, где в источнике отрицание: "
                f"{chunk.text!r}"
            )


# --------------------------------------------------------------------------- #
# 5. Таблица и её шапка
# --------------------------------------------------------------------------- #


def test_table_continuation_carries_header() -> None:
    """Таблица несёт свою шапку в каждом чанке, где есть её строки.

    Предотвращаемое искажение: продолжение таблицы приходит без имён столбцов, и
    значения читаются как безымянные (или приписываются чужим столбцам). Шапка
    допустима в ``context_prefix``: промпт печатает контекст, и чанк остаётся
    самодостаточным.
    """
    md = (
        "# Таблица\n\n"
        "| Параметр | Значение |\n"
        "|---|---|\n"
        + "".join(f"| P{index} | {index} |\n" for index in range(20))
    )
    chunks = _chunk(md, chunk_size=120)
    _assert_joined(chunks)
    assert len(chunks) > 1, "таблица не разрезана — свойство продолжения не проверено"

    for chunk in chunks:
        if "| P" not in chunk.text:
            continue
        assert "| Параметр | Значение |" in chunk.text or (
            "| Параметр | Значение |" in chunk.context_prefix
        ), f"продолжение таблицы без шапки: {chunk.text!r}"
